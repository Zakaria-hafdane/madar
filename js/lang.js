// ── Core ──────────────────────────────────────────────────────────────────────

const MADAR_LANG_KEY   = "madar-lang";
const SUPPORTED_LANGS  = new Set(["ar", "en", "fr"]);
let currentLang        = "ar";

function translate(key, lang) {
  lang = lang || currentLang;
  const entry = MADAR_TRANSLATIONS[key];
  if (!entry) return "";
  return entry[lang] || entry.ar || "";
}

function applyTranslations(lang) {
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const val = translate(el.getAttribute("data-i18n"), lang);
    if (val) el.textContent = val;
  });

  document.querySelectorAll("[data-i18n-html]").forEach(el => {
    const val = translate(el.getAttribute("data-i18n-html"), lang);
    if (val) el.innerHTML = val;
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const val = translate(el.getAttribute("data-i18n-placeholder"), lang);
    if (val) el.setAttribute("placeholder", val);
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach(el => {
    const val = translate(el.getAttribute("data-i18n-aria-label"), lang);
    if (val) el.setAttribute("aria-label", val);
  });
}

function updateLangButtons(lang) {
  document.querySelectorAll(".lb[data-lang]").forEach(btn => {
    btn.classList.toggle("on", btn.dataset.lang === lang);
  });
}

function setLang(lang) {
  const next  = SUPPORTED_LANGS.has(lang) ? lang : "ar";
  currentLang = next;
  const isRTL = next === "ar";

  try { localStorage.setItem(MADAR_LANG_KEY, next); } catch (_) {}

  document.documentElement.lang = next;
  document.documentElement.dir  = isRTL ? "rtl" : "ltr";

  updateLangButtons(next);
  applyTranslations(next);

  window.dispatchEvent(new CustomEvent("madar:langchange", { detail: { lang: next } }));
}

function initLang() {
  document.querySelectorAll(".lb[data-lang]").forEach(btn => {
    btn.addEventListener("click", () => setLang(btn.dataset.lang));
  });

  let saved = "ar";
  try {
    const v = localStorage.getItem(MADAR_LANG_KEY);
    if (v && SUPPORTED_LANGS.has(v)) saved = v;
  } catch (_) {}

  setLang(saved);
}

// Expose globally so inline handlers can call setLang()
window.setLang    = setLang;
window.madarI18n  = { translate, setLang, getCurrentLang: () => currentLang };

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", initLang, { once: true });
} else {
  initLang();
}
